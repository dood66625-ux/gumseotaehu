export const policySlugs = Object.keys(policies);
export default function PolicyDraft({ slug }: { slug: string }) {
  const p = policies[slug];
  if (!p) return null;
  return (
    <div className="page legal">
      <p className="eyebrow">POLICY DRAFT · 2026.11.22</p>
      <h1>{p.title}</h1>
      <p className="notice">
        실제 사업자 기준의 전문가 검토 전 초안입니다. 법률·세무 자문 또는 법적
        준수 완료를 의미하지 않습니다.
      </p>
      {slug === "business" && <BusinessInfo />}
      {p.sections.map((s) => (
        <section key={s.title}>
          <h2>{s.title}</h2>
          <p>{s.text}</p>
        </section>
      ))}
      {slug === "privacy" && (
        <section aria-labelledby="privacy-officer-title">
          <h2 id="privacy-officer-title">개인정보 문의 담당</h2>
          <p>개인정보보호 책임자: {business.privacyOfficer}</p>
          <p>
            연락 이메일:{" "}
            <a href={`mailto:${business.email}`}>{business.email}</a>
          </p>
          <p>
            열람·정정·삭제·처리정지 요청을 접수합니다. 비밀번호나 인증번호는
            보내지 마세요.
          </p>
        </section>
      )}
      <a className="button secondary" href="/help">
        문의·권리 행사 접수
      </a>
    </div>
  );
}
